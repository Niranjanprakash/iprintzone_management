-- ============================================================

-- 1. Create Jobs Table
CREATE TABLE IF NOT EXISTS public.jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_date DATE NOT NULL DEFAULT CURRENT_DATE,
    phone_number TEXT NOT NULL DEFAULT '',
    client_name TEXT NOT NULL,
    job_description TEXT NOT NULL DEFAULT '',
    quantity NUMERIC NOT NULL DEFAULT 1,
    c_rate_paise BIGINT NOT NULL DEFAULT 0,
    c_design_charge_paise BIGINT NOT NULL DEFAULT 0,
    c_total_paise BIGINT NOT NULL DEFAULT 0,
    svk_rate_paise BIGINT NOT NULL DEFAULT 0,
    svk_total_paise BIGINT NOT NULL DEFAULT 0,
    ipz_total_paise BIGINT NOT NULL DEFAULT 0,
    remarks TEXT NOT NULL DEFAULT '',
    expected_delivery_date DATE,
    actual_delivery_date DATE,
    delivery_status TEXT NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Create Payments Table
CREATE TABLE IF NOT EXISTS public.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
    account_type TEXT NOT NULL CHECK (account_type IN ('C', 'SVK')),
    amount_paise BIGINT NOT NULL DEFAULT 0,
    payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    payment_method TEXT NOT NULL DEFAULT 'Cash',
    reference_number TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Create Expenses Table
CREATE TABLE IF NOT EXISTS public.expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
    description TEXT NOT NULL DEFAULT '',
    amount_paise BIGINT NOT NULL DEFAULT 0,
    expense_date DATE NOT NULL DEFAULT CURRENT_DATE,
    notes TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Create Indexes for High Performance
CREATE INDEX IF NOT EXISTS idx_jobs_job_date ON public.jobs(job_date);
CREATE INDEX IF NOT EXISTS idx_jobs_delivery_status ON public.jobs(delivery_status);
CREATE INDEX IF NOT EXISTS idx_jobs_client_name ON public.jobs(client_name);
CREATE INDEX IF NOT EXISTS idx_payments_job_id ON public.payments(job_id);
CREATE INDEX IF NOT EXISTS idx_payments_account_type ON public.payments(account_type);
CREATE INDEX IF NOT EXISTS idx_payments_date ON public.payments(payment_date);
CREATE INDEX IF NOT EXISTS idx_expenses_job_id ON public.expenses(job_id);
CREATE INDEX IF NOT EXISTS idx_expenses_date ON public.expenses(expense_date);

-- 5. Enable Row Level Security (RLS) & Allow public anon access for app operations
ALTER TABLE public.jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.expenses ENABLE ROW LEVEL SECURITY;

-- Allow anon read/write access (for mobile app client with anon key)
DO $$
BEGIN
    DROP POLICY IF EXISTS "Allow anon all on jobs" ON public.jobs;
    CREATE POLICY "Allow anon all on jobs" ON public.jobs FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Allow anon all on payments" ON public.payments;
    CREATE POLICY "Allow anon all on payments" ON public.payments FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Allow anon all on expenses" ON public.expenses;
    CREATE POLICY "Allow anon all on expenses" ON public.expenses FOR ALL USING (true) WITH CHECK (true);
END $$;
